-- 개체 갈래 증분 재판정 — entity_mm_skill_label.material_hash 추가 (spec 104 · v307).
--
-- 배경: 개체 갈래 배치가 「무엇을 보고 판정했는지」를 남기지 않아, 다시 판정할 필요가 있는지
--   알 수 없었다. 그래서 매시간 구성원 많은 순 상위 N개를 무조건 다시 판정했다 —
--   재료가 그대로여도 LLM 을 부르고(헛일), N+1번째부터는 영영 판정하지 않고(굶주림),
--   같은 재료인데 갈래가 실행마다 조금씩 바뀌었다(흔들림).
--   비유: 도서관 사서가 매시간 「가장 두꺼운 책 500권」에 분류 스티커를 새로 붙이고,
--   501번째 책에는 한 번도 붙이지 않는 것과 같다.
--
-- 해결: 판정할 때 쓴 **재료의 지문**(재료 문자열의 SHA-256 16진 64자)을 행에 함께 남긴다.
--   다음 배치는 지문·스킬 판·문안 판이 모두 그대로인 (개체, 스킬)을 건너뛴다.
--   개체 임베딩(`entity_embedding.material_hash` · v306)이 이미 쓰는 방식과 같은 지문이다.
--
-- 🔴 **NULL 허용이 의도다.** NULL = 「지문이 없는 옛 판정」(이 칸이 생기기 전에 쓴 행) → 배치가
--   재선별 대상으로 본다. 그래서 이 마이그레이션 뒤 첫 실행은 노출 개체 전부를 한 번 다시 판정한다.
--   기존 행에 지금 재료의 지문을 **소급해 채우지 않는다** — 그 판정이 어떤 재료로 이뤄졌는지
--   알 수 없어 「확인 안 된 지문」이 생긴다(배치가 매시간 덮어쓴 이력이 있다).
--   같은 이유로 DEFAULT 도 두지 않는다.
--
-- 같은 (개체, 스킬)의 행들은 **같은 지문**을 가진다 — 판정 1회가 라벨 행 1..N개(multi)로
--   저장되고, 저장 함수가 그 행들에 같은 값을 쓴다. 값이 섞여 있으면(부분 실패·옛 코드 혼입)
--   배치가 「혼합」으로 보고 다시 판정한다.
--
-- 인덱스는 만들지 않는다 — 배치는 상태를 (개체, 스킬)별로 **표 전체를 한 번** 집계해 읽고
--   지문으로 행을 찾는 조회가 없다(표 규모 수천~만 행 · 순차 스캔이 맞다).
--
-- 🔴 **가역이다** — downgrade = 이 칸만 `DROP COLUMN`. 표와 기존 라벨 행은 그대로 남는다.
--   단 **지문 값은 사라진다** — 다시 upgrade 하면 모두 NULL 이라 첫 배치가 전량 다시 판정한다(라벨 행만 무손실).
-- 🔴 **코드와의 순서**: 새 코어(`replace_entity_labels`·`fetch_label_state`)는 이 칸을 조건 없이 읽고 쓴다 →
--   ① 배포는 **이 마이그레이션 먼저**, 새 코어를 담은 파이프(Airflow) 이미지는 그 뒤.
--   ② 되돌릴 때는 **코드(파이프 이미지) 먼저**, downgrade 는 그 뒤 — 거꾸로면 배치가 UndefinedColumn 으로 실패한다.
--   ③ 적용은 개체 갈래 배치가 돌지 않는 시간에(ALTER 가 표 잠금을 짧게 잡는다 · 열린 읽기 트랜잭션 뒤에서 기다릴 수 있다).
-- 멱등: ADD COLUMN IF NOT EXISTS — 재실행 안전.
-- 적용 순서: v306 이후(운영은 `upgrade v307_entity_label_hash` 로 리비전 지정).
-- =============================================================================

ALTER TABLE entity_mm_skill_label
