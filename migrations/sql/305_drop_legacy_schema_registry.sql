-- 레거시 `schema_registry` 제거 — 중복 레지스트리 정리 (v305).
--
-- 배경: ext_meta 거버넌스 레지스트리가 **두 벌** 있었다.
--   · `ext_meta_field_registry`(v291 · 정본) — 코드가 읽고 쓴다(`src/registry/`).
--   · `schema_registry`(v100 신설 · v220 시드 · v280·v290·v298 개정) — **레거시**.
--
-- 왜 지금 지우나(실측 2026-08-27):
--   ① **내용이 완전히 같다.** `(domain, meta_key)` 로 짝지어 14쌍 전수 대조 → `json_schema`·
--      `status`·`access_tier` 차이 **0건**. 한쪽만 있는 행도 없다.
--   ② **코드가 읽지 않는다.** 3레포(`src`·`processing`·`service`·`scripts`) 전수 grep 결과
--      실제 쿼리 0건이고, 남은 언급 2곳은 "레거시"라는 주석뿐이다.
--   ③ **유지 이유가 소멸했다.** CLAUDE.md 의 근거는 *"main 호환용 병행 유지"* 였고, 그 호환은
--      2026-07-22 main 이 분리본으로 전환되면서 끝났다(통합본은 `backup/main-monolith` 보존).
--
-- 🔴 **왜 그냥 두지 않나**: 같은 뜻의 테이블이 둘이면 누군가 레거시를 정본으로 오인한다.
--   실제 사례가 이 조사 중에 있었다 — 두 테이블을 `meta_key` 만으로 조인해 도메인별 2행이
--   교차곱을 만들어 "값이 다르다"는 잘못된 결론을 냈다(도메인을 넣어 다시 재고 정정). 용량은
--   0.04MB 로 문제가 아니고, 정리의 동기는 **개념 명확성**이다.
--
-- 가역성: downgrade 는 리비전 5개(v100·v220·v280·v290·v298)를 재현하지 않는다 — 대신 **현행
--   모양 그대로** 만들고 `ext_meta_field_registry` 에서 행을 복사한다. 두 테이블 내용이 같음을
--   위 ①에서 실측했으므로 이 복원이 원래 상태와 동일하다. 리비전 재현보다 짧고, 짧은 쪽이
--   되돌릴 때 실수가 적다.
--   ⚠️ `schema_id` 는 원래 값을 되살릴 수 없다(테이블이 사라지므로). 새 UUIDv7 이 아니라
--   `field_id` 를 그대로 쓴다 — 두 테이블이 같은 행을 가리키므로 대응이 유지되고, PK 값 자체를
--   참조하는 FK 는 없다(제약 조회로 확인).
--
-- 멱등: DROP TABLE IF EXISTS — 재실행 안전. 다른 테이블 무접촉(FK 참조 0 · 제약 조회로 확인).
-- 적용 순서: v304 이후.
-- ⚠️ **운영 적용 전 확인 필요**(사용자 결정 2026-08-27): dev 코드에는 참조가 없으나 운영 DB·
--   외부 도구에서 읽는 경로가 없는지는 이 리비전이 확인할 수 없다. 확인 후 적용한다.
-- =============================================================================

DROP TABLE IF EXISTS schema_registry;
