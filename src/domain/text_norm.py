"""표기 정규화 키 — **083 태그 패싯과 084 멀티모달 메타가 공유하는 단일 정본**.

같은 뜻인데 표기만 다른 문자열을 한 칸으로 묶기 위한 키를 만든다. 비유하면 주소를 우편번호로
바꾸는 일이다 — "서울시 강남구"·"서울 강남구" 는 사람 눈에 같은 곳이지만 문자열로는 다르다.
키를 통일해 두면 세는 것(건수)·거르는 것(필터)이 같은 기준을 쓴다.

**왜 별 모듈인가**: 083(검색 태그)과 084(멀티모달 개체 묶음)가 같은 규칙을 쓴다. 두 spec 이 각자
정의하면 파이썬 안에 규칙 사본이 둘 생기고, 한쪽만 고쳐지는 날 색인 키와 필터 키가 갈라진다
(083 plan §Global Constraints — 규칙 정본 1곳). 그래서 search/entity 어느 쪽도 아닌 **중립 도메인
모듈**에 둔다.

규칙(순서가 계약이다):
    1. ``NFKC`` 정규화 — 전각 문자를 반각으로(``ＡＢＣ``→``ABC``), 전각 공백(U+3000)도 보통 공백으로.
    2. **모든 공백 제거** — "전통 음식"→"전통음식"(1번이 먼저라야 전각 공백까지 지워진다).
    3. ``casefold`` — 영문 대소문자 병합. ``lower`` 보다 강하다(``Straße``→``strasse``).

정규화 후 빈 문자열이 되는 입력(공백뿐·빈 값)은 ``""`` 로 수렴시킨다 — **키가 아니라는 표식**이며,
색인·집계 호출부가 이 값 하나만 보고 배제한다.

⚠️ NFKC 자체의 병합 기여는 083 실측에서 0그룹이었다(어휘 5,084종 전수 — 병합 110그룹 전부 공백·
대소문자 발). 그래도 유지하는 이유는 전각 입력이 들어오는 날 조용히 갈라지지 않게 하는 보험이고,
파이썬 표준 라이브러리라 비용이 없기 때문이다(083 spec §① ⓒ).

설계 배경: ``specs/083-search-tag-facet`` §②
"""

from __future__ import annotations

import unicodedata


def normalize_text_key(s: str) -> str:
    """표기 차이를 흡수한 정규화 키를 만든다(NFKC → 공백 전제거 → casefold).

    멱등이다 — ``normalize_text_key(normalize_text_key(x)) == normalize_text_key(x)``. 색인 시점과
    필터 값 양쪽에서 같은 함수를 거치기 때문에 이 성질이 필요하다(두 번 통과한 키가 갈라지면
    필터가 아무것도 못 찾는다).

    Args:
        s: 원문 문자열(태그·개체명 등). ``None`` 같은 빈 값은 ``""`` 로 본다.

    Returns:
        정규화 키. 공백뿐이거나 빈 입력이면 ``""``(= 키 아님 · 호출부가 배제한다).
    """
    if not s:
        return ""
    # NFKC 를 먼저 — 전각 공백(U+3000)이 보통 공백이 된 뒤라야 아래 공백 제거가 그것도 지운다.
    normalized = unicodedata.normalize("NFKC", s)
    # split() 은 인자 없이 부르면 유니코드 공백 전부(스페이스·탭·개행)를 기준으로 쪼갠다 —
    # 이어 붙이면 "모든 공백 제거"가 된다.
    return "".join(normalized.split()).casefold()
