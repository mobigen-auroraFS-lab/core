@dataclass(frozen=True, slots=True)
class EntityTypeDef:
    """개체 타입 하나의 **정의문**(불변 · F05 · spec §10).

    무엇을 담나: 타입 이름 하나에 "이 뜻으로만 판정하라"는 정의(``definition``)와 "이건 아니다"는
    경계(``exclusion``)를 붙인 것이다. 이름만 주면 LLM 이 자기 상식으로 경계를 정해 같은 개체가
    자산마다 다른 타입으로 갈린다 — 경계 개체(조선=사건/조직 · 국립중앙박물관=장소/조직 …)의
    흔들림이 그래서 생겼고, 정의문을 붙이자 거의 전부 통일됐다(수치는 spec §10).

    비유하면 서식의 항목 설명이다. "직업" 칸만 있으면 사람마다 다르게 적지만, "직업: 지금 급여를
    받는 일(학생·구직 중은 제외)"이라고 적어 두면 답이 모인다.

    **저장 모양은 ``mm_skill.labels`` 의 라벨 하나와 같다**(``{code,name,definition,not}``) — 어휘를
    DB 로 옮길 때 그 행이 정본이 되고 이 객체는 그것을 코드로 읽어 들인 모양이다(085 저장소 공유 ·
    **판정 엔진은 공유하지 않는다**). 파이썬 예약어를 피해 JSON 키 ``not`` 만 ``exclusion`` 으로 둔다
    (``mm_classify.model.SkillLabel`` 과 같은 관례).
    """

    code: str  # 저장·조회용 코드(소문자 스네이크 · DB 라벨 code).
    name: str  # 판정 어휘로 쓰는 표시 이름(닫힌 5종 · LLM 이 이 표기로 답한다).
    definition: str  # "이 뜻으로만 판정한다" — 프롬프트에 그대로 실린다.
    exclusion: str  # "아닌 것" 경계 — 같은 줄 뒤에 붙어 나간다.

    def __post_init__(self) -> None:
        """빈 값을 거부한다(경계 fail-fast).

        정의문·경계가 비면 그 타입만 이름뿐인 옛 상태로 되돌아가는데, 프롬프트는 정상으로 보이므로
        판정이 흔들려도 원인을 찾기 어렵다 — 등록·조립 이전에 막는다.
        """
        for field_name, value in (
            ("code", self.code),
            ("name", self.name),
            ("definition", self.definition),
            ("exclusion", self.exclusion),
        ):
            if not isinstance(value, str) or not value.strip():
                raise ValueError(
                    f"타입 정의문의 {field_name} 가 비어 있다: {value!r} "
                    "(이름만 있는 어휘는 판정을 LLM 상식에 맡긴다 · spec §10)"
                )


