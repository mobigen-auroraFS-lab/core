EXCLUDED_ENTITIES: frozenset[str] = frozenset(normalize_text_key(name) for name in _EXCLUDED_NAMES)

# ② 지정·자격 스톱패턴 — 이 조각이 **키워드**에 들어 있으면 그 키워드는 판정에서 뺀다.
#   '올림픽 정식 종목' 하나 때문에 올림픽 묶음 절반이 종목 일반 문서였다(검증 §2).
#   정규화 키로 들고 있어 '정식종목'(붙여 쓴 표기)도 같은 패턴으로 걸린다.
#   ⚠️ '올림픽 금메달'(인물 자산)은 통과시킨다 — 패턴을 좁게 잡은 이유가 그 과잉 제거 방지다.
STOP_PATTERNS: tuple[str, ...] = tuple(
    normalize_text_key(pattern)
    for pattern in ("정식 종목", "세계문화유산", "인류무형문화유산")
)

# ③ 행정 접미 7종(고정 · 증식 없음). **긴 것부터** 나열한다 — '서울특별시' 에서 '시' 가 먼저
#   잡히면 base 가 '서울특별' 이 되어 병합이 어긋난다(최장 일치가 필요하다).
#   수기 별칭 사전은 도입하지 않는다(사용자 결정 2026-08-20 — 증식형 관리 부담). 접미는 고정
#   알고리즘이라 예외로 남긴 유일한 표기 규칙이다.
SUFFIXES: tuple[str, ...] = ("특별자치도", "특별자치시", "특별시", "광역시", "시", "군", "도")

# ③-1 접미 병합을 **적용하는 타입**(2026-08-24 결함 ③ 수정). 행정 접미는 지명의 것이므로 장소만
#   본다. 왜 필요한가: '시'·'군' 은 사람 이름·부대 이름·역사 용어의 끝 글자로도 흔하다. dev 색인
#   실측에서 그 셋이 행정 접미로 오인돼 몸통 항목이 만들어져 있었다 —
#   ``(인물,'리오넬메')→'리오넬 메시'``·``(조직,'영국해')→'영국 해군'``·``(사건,'한사')→'한사군'``.
#   그 칸이 있으면 '리오넬 메'·'영국 해' 같은 판정이 엉뚱한 개체로 흡수된다.
#   🔴 이 집합이 **확장 지점**이다 — 타입 어휘가 늘어 행정 단위를 쓰는 타입이 생기면 여기에 넣는다
#   (코드를 뒤져 조건문을 찾지 않아도 되게 상수로 둔다).
SUFFIX_MERGE_TYPES: frozenset[str] = frozenset({"장소"})

# ③-2 병합 후보가 되는 **몸통 최소 길이**(글자 · 2026-08-24 결함 ② 수정). dev 색인에
#   ``(장소,'독')→'독도'``·``(장소,'인')→'인도'`` 가 있었다 — '독'·'인' 이 장소로 판정되는 일은
#   드물지만 한 번이라도 나오면 엉뚱한 자산이 독도·인도 묶음으로 들어간다. 1글자 지명의 병합으로
#   얻는 것보다 오병합으로 잃는 것이 크다. 2 로 두면 '제주'·'경주'·'서울'(2글자)은 그대로 유효하다.
#   비유하면 이름표의 앞글자다 — '김' 하나로 사람을 찾으면 남의 짐을 들고 간다.
MIN_BASE_LENGTH = 2


@dataclass(frozen=True, slots=True)
class ExtractedEntity:
    """키워드 하나에서 뽑은 개체 판정(불변).

    "개체 추출"의 결과 한 건이다 — 저장·노출되는 레코드(멀티모달 메타)의 재료이며, 여기서
    ``keyword`` 는 근거로 ``reason`` 스탬프(``kw=``)에 그대로 실린다(spec §4).

    닫힌 어휘·빈 값 검사를 **경계에서** 한다(fail-fast) — 판정 해석부(``judge``)는 어휘 밖 값을
    "그 키워드 판정 없음"으로 흡수하고, 그래도 새어 들어오면 이 생성자가 막는다(이중 방어).
    """

    keyword: str  # 원문 키워드(판정의 출처).
    name: str  # LLM 이 고른 개체 표준표기 = 대표 표기 후보.
    entity_type: str  # 닫힌 5종(``ENTITY_TYPES``).

    def __post_init__(self) -> None:
        """닫힌 어휘·빈 값을 검사한다(위반이면 ``ValueError``)."""
        if not self.keyword or not self.keyword.strip():
            raise ValueError("키워드가 비어 있다 — reason 스탬프의 근거를 잃는다")
        if not normalize_text_key(self.name):
            raise ValueError(f"개체 표기가 비어 있다: {self.name!r}")
        if self.entity_type not in ENTITY_TYPES:
            raise ValueError(
                f"개체 타입이 닫힌 어휘 밖이다: {self.entity_type!r} (허용 {ENTITY_TYPE_ORDER})"
            )

    @property
    def uid(self) -> str:
        """표기 키(``entity_uid``) — 083/084 공용 ``normalize_text_key`` 결과."""
        return normalize_text_key(self.name)


def is_excluded_entity(name: str) -> bool:
    """광역 제외 목록(V1)에 해당하는 개체 표기인가.

    Args:
        name: 개체 표준표기. 표기 차이(공백·전각·대소문자)는 정규화 키로 흡수한다.

    Returns:
        제외 대상이면 ``True``(그 판정은 버린다).
    """
    return normalize_text_key(name) in EXCLUDED_ENTITIES


def is_stopped_keyword(keyword: str) -> bool:
    """지정·자격 스톱패턴을 품은 키워드인가.

    Args:
        keyword: 원문 키워드. 정규화 키로 바꿔 **부분 문자열**로 본다('올림픽 정식 종목' 안의
            '정식 종목' 을 잡아야 하므로 완전 일치로는 안 된다).

    Returns:
        스톱 대상이면 ``True``(그 키워드에서 나온 판정은 버린다 — 자산 전체를 버리는 것이 아니다).
    """
    key = normalize_text_key(keyword)
    return any(pattern in key for pattern in STOP_PATTERNS)


def _base_uid(uid: str) -> str | None:
    """접미가 붙은 표기 키에서 접미를 뗀 몸통을 돌려준다(최장 일치).

    Args:
        uid: 표기 키(정규화된 값).

    Returns:
        몸통 표기 키. 병합 후보가 아니면 ``None`` — ①접미가 없는 표기 ②접미를 떼면 빈 문자열이
        되는 표기(개체명이 '도' 한 글자 등) ③몸통이 ``MIN_BASE_LENGTH`` 미만인 표기('독도'→'독' ·
        2026-08-24 결함 ② 수정)가 그렇다. 세 경우를 한 자리에서 판단하는 이유: "이 표기가 대표할
        몸통이 있는가"는 하나의 질문이고, 색인 조립부가 조건을 흩어 들고 있으면 한쪽만 고쳐진다.
    """
    for suffix in SUFFIXES:  # 긴 접미부터 — 최장 일치
        key = normalize_text_key(suffix)
        if uid.endswith(key) and len(uid) - len(key) >= MIN_BASE_LENGTH:
            return uid[: -len(key)]
    return None


def build_official_name_index(
    known: Iterable[tuple[str, str] | tuple[str, str, int]],
) -> Mapping[tuple[str, str], str]:
    """"**(타입, 몸통 표기 키) → 공식 표기**" 색인을 만든다(순수·결정적).

    🔴 **용법: 배치 시작에 한 번 만들어 자산 루프 전체에서 재사용한다.** 자산 하나를 처리할 때마다
    이 함수를 부르면 자산 수 × 등록 개체 수만큼 일이 생긴다 — 자산 10만 × 개체 10만이면 100억
    연산이다(2026-08-24 결함 ②: 예전 ``apply_rules`` 가 판정분 + 등록 표기 전량으로 매번 대응표를
    다시 만들었다). 비유하면 전화번호부다. 전화 한 통마다 번호부를 새로 인쇄하지 않고, 한 권 만들어
    두고 찾아본다. ``apply_rules(official_index=...)`` 는 이 색인을 **찾아보기만** 한다.

    🔴 **키에 타입이 들어가는 이유**(결함 ①): 표기만 보면 타입이 다른 동음이의가 잘못 합쳐진다 —
    ``[사건] 경주``(경마)가 등록된 ``[장소] 경주시`` 로 끌려갔다. 별칭 매칭
    (``persist.fetch_registered_alias_index``)은 이미 (타입, 표기 키) 스코프인데 접미 병합만
    어긋나 있었다. 타입을 키에 넣으면 그 계열의 실수가 원천에서 불가능해진다.

    🔴 **선택 규칙 = 묶음이 큰 표기**(2026-08-24 결함 ① 수정). 공식형 후보가 여럿이면
    ``(자산이 많이 붙은 쪽 → 긴 접미 → 표기 키 사전순)`` 순서로 하나를 고른다. 옛 규칙은 "긴 접미"가
    첫 축이었는데, dev 색인 실측에서 그것이 실제 묶음을 배신했다 — ``(장소,'제주')`` 의 공식형이
    자산이 거의 없는 '제주특별자치도' 로 정해졌고 알찬 묶음은 '제주도' 였다(강원도도 같은 상태).
    이 색인의 목적이 "이미 자산이 붙은 곳으로 합류"(§구현 확정 2)이므로 크기가 첫 축이어야 한다.
    비유하면 모임 장소다 — 여러 명 있는 방과 한 명 있는 방이 있으면 늦게 온 사람은 많은 쪽으로 간다. 크기가 같으면 옛 규칙(긴 접미 → 사전순)이 그대로 이어받아
    같은 입력이면 언제나 같은 하나가 나온다(헌법 3조).

    🔴 **장소 타입만**(``SUFFIX_MERGE_TYPES`` · 결함 ③) · **몸통 최소 2글자**
    (``MIN_BASE_LENGTH`` · 결함 ②). 두 문턱을 이 함수 안에 두는 이유: 색인을 만드는 곳이 한 곳이라
    여기서 막으면 주입 색인·지역 색인 두 경로가 자동으로 같은 규칙을 쓴다.

    Args:
        known: ``(개체 타입, 개체 표기)`` 또는 ``(개체 타입, 개체 표기, 묶음 크기)``. 보통 **이미
            등록된 메타**의 대표 표기 + 별칭이며(``persist.fetch_official_name_index`` 가 DB 에서
            읽어 온다), 판정 목록으로 지역 색인을 만들 때도 같은 함수를 쓴다. 접미가 없는 표기는
            아무 몸통도 대표하지 않으므로 조용히 빠진다(색인이 불필요하게 커지지 않는다).
            **묶음 크기 = 그 표기의 개체에 붙어 있는 자산 수**이며 생략·0·음수는 모두 **0**(=붙은
            자산 없음)으로 흡수한다 — 그래서 크기를 모르는 호출부(자산 하나 안의 판정으로 만드는
            지역 색인처럼 크기 개념이 없는 경우)는 전부 동점이 되어 **옛 규칙 그대로** 동작한다.

    Returns:
        ``{(타입, 몸통 표기 키): 공식 표기}``. 후보가 없으면 빈 dict. 표기는 입력 문자열
        **그대로** 담는다(다듬기·표시 규칙은 저장 계층 ``persist.ensure_entity_node`` 의 몫이다).
    """
    # 몸통별 후보를 모은 뒤 정렬로 고른다 — 입력 순서에 결과가 흔들리지 않게(결정성).
    candidates: dict[tuple[str, str], list[tuple[int, int, str, str]]] = {}
    for entry in known:
        entity_type, name = entry[0], entry[1]
        if entity_type not in SUFFIX_MERGE_TYPES:
            continue  # 결함 ③ — 행정 접미는 지명의 것이다
        # 크기 미지정(2튜플)·음수는 0 으로 — 폴백이 있어야 옛 호출부가 그대로 돈다.
        size = max(0, int(entry[2])) if len(entry) > 2 else 0
        uid = normalize_text_key(name)
        base = _base_uid(uid)  # 접미 없음·몸통 1글자는 여기서 걸린다(결함 ②)
        if base is None:
            continue
        candidates.setdefault((entity_type, base), []).append(
            (size, len(uid) - len(base), uid, name)
        )
    return {
        # 묶음이 큰 것 우선(-크기) → 접미가 긴 것(-길이) → 표기 키 사전순. 항상 같은 하나가 골라진다.
        key: min(items, key=lambda item: (-item[0], -item[1], item[2]))[3]
        for key, items in candidates.items()
    }


def apply_rules(
    judged: Sequence[ExtractedEntity],
    *,
    official_index: Mapping[tuple[str, str], str] | None = None,
) -> tuple[ExtractedEntity, ...]:
    """판정 목록에 결정 규칙 3단을 적용한다(제외 → 스톱 → 접미 병합 · 순수).

    **적용 순서가 계약이다.** 제외를 먼저 해야 제외 대상이 병합의 목표로 되살아나지 않는다 —
    예를 들어 '한국' 이 먼저 떨어지고 나면 다른 짧은 표기가 '한국' 으로 합쳐질 길이 없다.
    마지막에 **(타입, 표기 키)** 가 같은 판정을 하나로 접는다: 키워드 13개가 모두 같은 개체를
    가리키면 개체는 하나이고 자산→개체 엣지도 하나다(유니크 (src,dst,kind) · spec §4).

    입력 목록은 **자산 하나 분량**을 넘기는 것이 기본 용법이다(중복 접기가 자산 안에서 뜻을
    갖는다). 여러 자산 분량을 한꺼번에 넘기면 서로 다른 자산의 판정이 접혀 버리므로 주의한다.

    Args:
        judged: 판정 목록(보통 자산 하나에서 나온 것). 순서를 보존한다 — 남는 대표 키워드가
            입력 순서의 첫 번째로 정해지므로, 호출부는 키워드 목록 순서를 유지해 넘긴다(결정성).
        official_index: ``build_official_name_index`` 가 만든 **(타입, 몸통 표기 키) → 공식 표기**
            색인(선택). 🔴 **배치 시작에 한 번 만든 것을 계속 넘긴다** — 이 함수는 색인을 훑거나
            복사하지 않고 **찾아보기만** 하므로 자산 수에 비례해 비용이 늘지 않는다. 무엇을 위한
            힌트인가: 증분 배치에서는 공식형('서울특별시')이 지난 배치의 노드로만 남아 있고 이번
            판정에는 짧은 표기('서울')만 온다(실측에서 '서울'과 '서울특별시'는 **다른 자산**에서
            나와 자산 안에서는 만나지 않았다). 미주입·빈 색인이면 병합은 ``judged`` 안에서만 일어
            난다(기존 동작).

    Returns:
        정제된 판정 튜플. 입력 목록은 변형하지 않는다(전부 새 객체·불변).
    """
    # ①② 제외·스톱 — 둘 다 "그 판정을 버린다"이므로 한 번에 훑는다(순서 무관·결과 동일).
    survivors = [
        entity
        for entity in judged
        if not is_stopped_keyword(entity.keyword) and not is_excluded_entity(entity.name)
    ]
    # ③ 접미 병합 — 자산 안에서 동시 등장한 표기끼리의 색인은 **여기서** 만든다(N = 그 자산의 판정
    #    수로 수십 규모라 자산 루프 안에서 만들어도 값이 싸다). 등록된 전체 개체 색인은 호출부가
    #    배치 시작에 한 번 만들어 넘긴다(결함 ② — 여기서 만들면 자산마다 전체를 다시 조립한다).
    #    지역 색인에는 **묶음 크기를 주지 않는다**(2튜플) — 자산 하나 안에서는 "자산이 몇 건 붙어
    #    있나"가 정의되지 않는다. 그래서 전부 동점이 되어 옛 규칙(긴 접미 → 사전순)으로 뽑힌다.
    local_index = build_official_name_index(
        (entity.entity_type, entity.name) for entity in survivors
    )

    merged: list[ExtractedEntity] = []
    seen: set[tuple[str, str]] = set()
    for entity in survivors:
        # 짧은 표기(= 몸통)면 공식형으로 갈아탄다. 접미를 **붙이지는 않는다** — 어떤 접미가
        # 공식인지는 규칙이 알 수 없고(서울시/서울특별시), 반대로 깎으면 '제주도'가 '제주'가 되어
        # 합격선(제주도 묶음)의 이름이 달라진다.
        #
        # 🔴 우선순위 = **주입 색인(기존 노드 표기) > 자산 내 공식형**(spec §구현 확정 2). 기존
        #    노드에는 이미 자산이 붙어 있으므로 그쪽으로 합류시켜야 묶음이 갈라지지 않고, 표기
        #    1회 고정(spec §4)도 지켜진다. 공식형 선호는 "같은 판정 안 동시 등장"에만 적용한다.
        # ⚠️ 두 색인을 dict 로 **합치지 않는다** — 합치기(``{**a, **b}``)는 주입 색인 전체를 자산
        #    마다 복사하는 것이라 결함 ② 를 그대로 되살린다. 룩업 두 번으로 끝낸다.
        lookup = (entity.entity_type, entity.uid)
        name = None if official_index is None else official_index.get(lookup)
        if name is None:
            name = local_index.get(lookup, entity.name)
        resolved = entity if name == entity.name else replace(entity, name=name)
        key = (resolved.entity_type, resolved.uid)
        if key in seen:
            continue  # 같은 개체를 가리키는 다른 키워드 — 첫 판정만 남긴다(대표 키워드 고정).
        seen.add(key)
        merged.append(resolved)
    return tuple(merged)


